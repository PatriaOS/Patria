/**
 * Reads docs/trust/*.md and writes typed TrustDocument modules for offline UI.
 * Run from patria-app/: npm run trust:content
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = join(here, '..');
const docsDir = join(appRoot, '..', 'docs', 'trust');
const outDir = join(appRoot, 'src', 'features', 'trust', 'generated');

function parseInline(raw) {
  const spans = [];
  const re = /\*\*(.+?)\*\*/g;
  let last = 0;
  let match;
  while ((match = re.exec(raw)) !== null) {
    if (match.index > last) {
      spans.push({ text: raw.slice(last, match.index) });
    }
    spans.push({ text: match[1], bold: true });
    last = match.index + match[0].length;
  }
  if (last < raw.length) {
    spans.push({ text: raw.slice(last) });
  }
  return spans.length > 0 ? spans : [{ text: raw }];
}

function stripOuterItalics(line) {
  const trimmed = line.trim();
  if (trimmed.startsWith('*') && trimmed.endsWith('*') && !trimmed.startsWith('**')) {
    return trimmed.slice(1, -1);
  }
  return null;
}

function parseTrustMarkdown(markdown) {
  const lines = markdown.replace(/\r\n/g, '\n').split('\n');
  const blocks = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i] ?? '';
    const trimmed = line.trim();
    if (trimmed.length === 0) {
      i += 1;
      continue;
    }
    if (trimmed.startsWith('### ')) {
      blocks.push({ type: 'h3', text: trimmed.slice(4).trim() });
      i += 1;
      continue;
    }
    if (trimmed.startsWith('## ')) {
      blocks.push({ type: 'h2', text: trimmed.slice(3).trim() });
      i += 1;
      continue;
    }
    if (trimmed.startsWith('# ')) {
      blocks.push({ type: 'h1', text: trimmed.slice(2).trim() });
      i += 1;
      continue;
    }
    const italic = stripOuterItalics(trimmed);
    if (italic !== null && !trimmed.startsWith('- ') && !trimmed.startsWith('* ')) {
      blocks.push({ type: 'lede', spans: parseInline(italic) });
      i += 1;
      continue;
    }
    if (trimmed.startsWith('- ')) {
      const items = [];
      while (i < lines.length) {
        const bullet = (lines[i] ?? '').trim();
        if (!bullet.startsWith('- ')) {
          break;
        }
        items.push(parseInline(bullet.slice(2)));
        i += 1;
      }
      blocks.push({ type: 'ul', items });
      continue;
    }
    const para = [trimmed];
    i += 1;
    while (i < lines.length) {
      const next = (lines[i] ?? '').trim();
      if (
        next.length === 0 ||
        next.startsWith('#') ||
        next.startsWith('- ') ||
        stripOuterItalics(next) !== null
      ) {
        break;
      }
      para.push(next);
      i += 1;
    }
    blocks.push({ type: 'p', spans: parseInline(para.join(' ')) });
  }
  return blocks;
}

const docs = [
  {
    id: 'how-patria-protects',
    sourceFile: 'HOW_PATRIA_PROTECTS_YOUR_FAMILY.md',
    outName: 'howPatriaProtects.ts',
    exportName: 'howPatriaProtectsDocument',
  },
  {
    id: 'privacy-statement',
    sourceFile: 'PRIVACY_STATEMENT.md',
    outName: 'privacyStatement.ts',
    exportName: 'privacyStatementDocument',
  },
];

mkdirSync(outDir, { recursive: true });

for (const doc of docs) {
  const markdown = readFileSync(join(docsDir, doc.sourceFile), 'utf8');
  const blocks = parseTrustMarkdown(markdown);
  const payload = {
    id: doc.id,
    sourceFile: doc.sourceFile,
    blocks,
  };
  const body = `/* Generated by scripts/generate-trust-content.mjs — do not edit by hand. */
import type { TrustDocument } from '../trustContent';

export const ${doc.exportName} = ${JSON.stringify(payload, null, 2)} as const satisfies TrustDocument;
`;
  writeFileSync(join(outDir, doc.outName), `${body}\n`);
  console.log(`Wrote ${doc.outName} (${blocks.length} blocks)`);
}
